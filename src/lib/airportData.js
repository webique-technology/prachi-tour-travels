export function getAirportTourBySlug(rawSlug) {
  if (!rawSlug) return null;
  const cleanSlug = String(rawSlug).toLowerCase().trim().replace(/\/$/, "");
  return (
    airportToursData.find((t) => t.slug.toLowerCase() === cleanSlug) || null
  );
}

export function getAllAirportSlugs() {
  return airportToursData.map((t) => ({ slug: t.slug }));
}

