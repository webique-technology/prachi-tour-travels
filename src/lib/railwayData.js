export function getRailwayTourBySlug(rawSlug) {
  if (!rawSlug) return null;
  const cleanSlug = String(rawSlug).toLowerCase().trim().replace(/\/$/, "");
  return (
    railwayToursData.find((t) => t.slug.toLowerCase() === cleanSlug) || null
  );
}

export function getAllRailwaySlugs() {
  return railwayToursData.map((t) => ({ slug: t.slug }));
}

